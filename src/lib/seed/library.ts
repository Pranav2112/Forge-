import type { FoodSeed } from "@/lib/seed/catalog";

type Dish = [
  key: string,
  name: string,
  kcal: number,
  protein: number,
  carbs: number,
  fat: number,
  prep: string,
  aliases: string,
  notes: string,
  estimate?: boolean,
  unit?: string,
  serving?: number,
  fiber?: number,
];

function row(dish: Dish): FoodSeed {
  const [key, name, calories, proteinG, carbsG, fatG, preparation, aliases, notes, estimate = true, servingUnit = "g", servingSize = 100, fiberG = 0] = dish;
  return {
    key,
    name,
    brand: "",
    servingSize,
    servingUnit,
    gramsPerServing: servingUnit === "piece" ? null : servingSize,
    calories,
    proteinG,
    carbsG,
    fatG,
    fiberG,
    sugarG: 0,
    sodiumMg: 0,
    hasSodium: false,
    source: estimate
      ? "Home-style estimate. Edit the food if your recipe differs."
      : "USDA FoodData Central, typical value per stated serving",
    isEstimate: estimate,
    isFavorite: false,
    preparation,
    aliases,
    notes,
  };
}

